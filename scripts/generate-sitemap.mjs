import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {SUPPORTED_LANGS, PAGE_META, publicUrl} from '../public/party/locale.mjs';
import {ogImageUrl} from '../public/party/seo.mjs';

const origin = 'https://trickortake.com';
const xml = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&apos;'}[c]));

// Generate reciprocal language groups from the same registry as the router.
// Omit lastmod rather than inventing a new content date on every deployment.
export function renderSitemap() {
  const entries = [];
  for (const page of ['', 'privacy', 'terms']) {
    const alternatives = [...SUPPORTED_LANGS.map(lang => ({lang: PAGE_META[lang].htmlLang, href: publicUrl(origin, lang, page)})),
      {lang:'x-default', href:publicUrl(origin, 'en', page)}];
    for (const lang of SUPPORTED_LANGS) {
      entries.push(['  <url>', `    <loc>${xml(publicUrl(origin, lang, page))}</loc>`,
        ...alternatives.map(link => `    <xhtml:link rel="alternate" hreflang="${link.lang}" href="${xml(link.href)}"/>`),
        ...(page ? [] : ['    <image:image>', `      <image:loc>${xml(ogImageUrl(origin, lang))}</image:loc>`, '    </image:image>']),
        '  </url>'].join('\n'));
    }
  }
  return ['<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by npm run sitemap. Public, canonical landing pages only. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
    ...entries, '</urlset>', ''].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../public/sitemap.xml', import.meta.url), renderSitemap());
  console.log(`Generated ${SUPPORTED_LANGS.length * 3} canonical pages with complete language alternatives.`);
}
